interface ZipOptions {
  method?: number; // 8 = deflate, 0 = stored; other values produce unsupported entries
  flags?: number;
  declaredSize?: number; // overrides the uncompressed size written to the headers
  descriptor?: 'signed' | 'unsigned'; // sizes in a data descriptor after the data (flag bit 3)
  prefix?: Buffer; // bytes before the first entry; offsets are shifted to point past them
  gap?: Buffer; // bytes between the last entry and the central directory
  unlisted?: string[]; // entries written to the archive but left out of the central directory
  afterStream?: Buffer; // bytes appended to each deflated payload, after the end of the deflate stream
}

/** Builds a ZIP archive with the given entries (synthetic fixture). CRCs are written as 0. */
function zip(
  files: Record<string, string | Buffer>,
  {
    method = 8,
    flags = 0,
    declaredSize,
    descriptor,
    prefix = Buffer.alloc(0),
    gap,
    unlisted = [],
    afterStream = Buffer.alloc(0),
  }: ZipOptions = {},
): Buffer {
  const locals: Buffer[] = [prefix];
  const central: Buffer[] = [];
  const entryFlags = descriptor ? flags | 0x8 : flags;
  let offset = prefix.length;
  for (const [name, content] of Object.entries(files)) {
    const data = Buffer.from(content);
    const body = method === 8 ? Buffer.concat([deflateRawSync(data), afterStream]) : data;
    const size = declaredSize ?? data.length;
    const nameBytes = Buffer.from(name);
    const local = Buffer.alloc(30);
    local.writeUInt32LE(0x04034b50, 0);
    local.writeUInt16LE(entryFlags, 6);
    local.writeUInt16LE(method, 8);
    if (!descriptor) {
      local.writeUInt32LE(body.length, 18);
      local.writeUInt32LE(size, 22);
    }
    local.writeUInt16LE(nameBytes.length, 26);
    const trailer = descriptor === 'signed' ? Buffer.alloc(16) : descriptor ? Buffer.alloc(12) : Buffer.alloc(0);
    if (descriptor === 'signed') trailer.writeUInt32LE(0x08074b50, 0);
    if (descriptor) {
      trailer.writeUInt32LE(body.length, trailer.length - 8);
      trailer.writeUInt32LE(size, trailer.length - 4);
    }
    const entry = Buffer.alloc(46);
    entry.writeUInt32LE(0x02014b50, 0);
    entry.writeUInt16LE(entryFlags, 8);
    entry.writeUInt16LE(method, 10);
    entry.writeUInt32LE(body.length, 20);
    entry.writeUInt32LE(size, 24);
    entry.writeUInt16LE(nameBytes.length, 28);
    entry.writeUInt32LE(offset, 42);
    locals.push(local, nameBytes, body, trailer);
    if (!unlisted.includes(name)) central.push(entry, nameBytes);
    offset += 30 + nameBytes.length + body.length + trailer.length;
  }
  if (gap) {
    locals.push(gap);
    offset += gap.length;
  }
  const directory = Buffer.concat(central);
  const count = Object.keys(files).length - unlisted.length;
  const end = Buffer.alloc(22);
  end.writeUInt32LE(0x06054b50, 0);
  end.writeUInt16LE(count, 8);
  end.writeUInt16LE(count, 10);
  end.writeUInt32LE(directory.length, 12);
  end.writeUInt32LE(offset, 16);
  return Buffer.concat([...locals, directory, end]);
}

/** Returns a copy of a synthetic archive with one field of its end record overwritten. */
function withEndField(archive: Buffer, field: number, value: number, bytes: 2 | 4): Buffer {
  const copy = Buffer.from(archive);
  const at = copy.length - 22 + field;
  if (bytes === 2) copy.writeUInt16LE(value, at);
  else copy.writeUInt32LE(value, at);
  return copy;
}

const embedded = (data: Record<string, string>) =>
  `<template id="playwrightReportBase64">data:application/zip;base64,${zip(data).toString('base64')}</template>`;

/** Writes a synthetic report folder: index.html embedding `reportData`, plus extra files. */
function writeReport(dir: string, reportData: Record<string, string>, files: Record<string, string | Buffer> = {}) {
  mkdirSync(dir, { recursive: true });
  writeFileSync(join(dir, 'index.html'), `<html>${embedded(reportData)}</html>`);
  for (const [name, content] of Object.entries(files)) {
    mkdirSync(dirname(join(dir, name)), { recursive: true });
    writeFileSync(join(dir, name), content);
  }
  return dir;
}

// Hard limits for child processes. spawnSync blocks the worker, so Playwright's own test timeout
// cannot interrupt a hung child. The limits of all runs in one test add up to less than that
// test's timeout (at most three CLI runs in a 30 s test; one nested run plus one CLI run in 120 s).
const CLI_TIMEOUT_MS = 8_000;
const NESTED_RUN_TIMEOUT_MS = 90_000;

interface ChildRun {
  code: number | null;
  timedOut: boolean;
  output: string;
}

/** Runs node with the given arguments and a hard timeout (the child is killed when it expires). */
function runNode(args: string[], timeout: number, env?: NodeJS.ProcessEnv): ChildRun {
  const run = spawnSync(process.execPath, args, { encoding: 'utf8', timeout, ...(env && { env }) });
  return {
    code: run.status,
    timedOut: (run.error as NodeJS.ErrnoException | undefined)?.code === 'ETIMEDOUT',
    output: `${run.stdout ?? ''}${run.stderr ?? ''}`,
  };
}

/** Why a child run failed, with credential patterns and the fake secret masked and output shortened. */
function describeFailure(run: ChildRun, timeout: number): string {
  const reason = run.timedOut ? `timed out after ${timeout} ms` : `exited with status ${run.code}`;
  return `${reason}\n${redact(run.output).replaceAll(SECRET, '<redacted>').slice(-2000)}`;
}

/** Runs the real CLI entry point the way the workflow does (node with type stripping). */
function runCli(script: string, args: string[]) {
  const run = runNode(['--experimental-strip-types', '--no-warnings', script, ...args], CLI_TIMEOUT_MS);
  expect(run.timedOut, `scanner CLI ${describeFailure(run, CLI_TIMEOUT_MS)}`).toBe(false);
  return { code: run.code, output: run.output };
}

