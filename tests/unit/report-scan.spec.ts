test.describe('readZip', () => {
  test('reads stored and deflated entries', async () => {
    const { readZip } = await load();

    expect(readZip(zip({ 'a.txt': 'alpha' }, { method: 0 }))).toEqual([{ name: 'a.txt', data: Buffer.from('alpha') }]);
    expect(readZip(zip({ 'b.json': '{"ok":true}' }))).toEqual([{ name: 'b.json', data: Buffer.from('{"ok":true}') }]);
  });

  test('fails closed on malformed or unsupported archives', async () => {
    const { readZip, ScanError } = await load();

    expect(() => readZip(Buffer.from('not a zip'))).toThrow(ScanError);
    expect(() => readZip(zip({ 'a.txt': 'alpha' }).subarray(10))).toThrow(ScanError);
    expect(() => readZip(zip({ 'a.txt': 'alpha' }, { method: 12 }))).toThrow('unsupported ZIP compression method 12');
    expect(() => readZip(zip({ 'a.txt': 'alpha' }, { method: 0, flags: 1 }))).toThrow('encrypted ZIP entries');
  });

  test('caps decompression at the declared size and rejects size mismatches', async () => {
    const { readZip, ScanError } = await load();
    const large = 'x'.repeat(100_000);

    // Declares 10 bytes but inflates to 100 000: inflation stops at the cap instead of expanding.
    expect(() => readZip(zip({ 'bomb.txt': large }, { declaredSize: 10 }))).toThrow(ScanError);
    // Declares more than it holds.
    expect(() => readZip(zip({ 'short.txt': 'abc' }, { declaredSize: 50 }))).toThrow('ZIP entry size mismatch');
    // Declares more than the scan limit allows: rejected before any inflation.
    expect(() => readZip(zip({ 'huge.txt': 'abc' }, { declaredSize: 0xfffffff0 }))).toThrow(
      'larger than the scan limit',
    );
  });

  test('rejects directory entries that contain data', async () => {
    const { readZip } = await load();

    expect(readZip(zip({ 'folder/': '' }, { method: 0 }))).toEqual([]);
    expect(() => readZip(zip({ 'folder/': kv('token', SECRET) }, { method: 0 }))).toThrow(
      'ZIP directory entry contains data',
    );
  });

  test('enforces the cumulative decompressed-size budget across entries', async () => {
    const { readZip, createBudget } = await load();
    const archive = zip({ 'a.txt': 'x'.repeat(60), 'b.txt': 'y'.repeat(60) });

    expect(readZip(archive, createBudget(120))).toHaveLength(2);
    // Each entry fits on its own, but together they exceed the budget: rejected before the second
    // entry is inflated.
    expect(() => readZip(archive, createBudget(100))).toThrow('report is larger than the scan limit');
  });
});

test.describe('readZip: every byte must be accounted for (synthetic archives)', () => {
  const clean = () => zip({ 'a.txt': 'alpha', 'b.txt': 'bravo' });
  const hidden = () => zip({ 'secret.json': kv('token', SECRET) }); // deflated: not visible as text

  test('reads entries with and without data descriptors, with or without the signature', async () => {
    const { readZip } = await load();
    const expected = [
      { name: 'a.txt', data: Buffer.from('alpha') },
      { name: 'b.txt', data: Buffer.from('bravo') },
    ];

    for (const descriptor of ['signed', 'unsigned'] as const) {
      for (const method of [0, 8]) {
        expect(readZip(zip({ 'a.txt': 'alpha', 'b.txt': 'bravo' }, { descriptor, method })), descriptor).toEqual(
          expected,
        );
      }
    }
    expect(readZip(clean())).toEqual(expected);
  });

  test('rejects missing or mismatched data descriptors', async () => {
    const { readZip } = await load();
    const directoryOffset = (archive: Buffer) => archive.readUInt32LE(archive.length - 22 + 16);
    // Flag bit 3 set, but the 12-byte descriptor before the central directory is removed.
    const withDescriptor = zip({ 'a.txt': 'alpha' }, { descriptor: 'unsigned' });
    const cut = directoryOffset(withDescriptor) - 12;
    const withoutDescriptor = withEndField(
      Buffer.concat([withDescriptor.subarray(0, cut), withDescriptor.subarray(cut + 12)]),
      16,
      cut,
      4,
    );
    // Descriptor compressed size that disagrees with the central directory.
    const wrong = zip({ 'a.txt': 'alpha' }, { descriptor: 'signed' });
    wrong.writeUInt32LE(999, directoryOffset(wrong) - 8);

    expect(() => readZip(withoutDescriptor)).toThrow('ZIP data descriptor does not match the central directory');
    expect(() => readZip(wrong)).toThrow('ZIP data descriptor does not match the central directory');
  });

  test('rejects plain-text credential data appended after a valid archive', async () => {
    const { readZip } = await load();

    expect(() => readZip(Buffer.concat([clean(), Buffer.from(kv('token', SECRET))]))).toThrow(
      'unexpected data after its end',
    );
  });

  test('rejects a second archive appended after, or embedded before, the listed entries', async () => {
    const { readZip } = await load();
    // Appended: the last end record belongs to the second archive, whose offsets do not fit.
    expect(() => readZip(Buffer.concat([clean(), hidden()]))).toThrow();
    // Appended without its end record: the first archive's end record is no longer last.
    expect(() => readZip(Buffer.concat([clean(), hidden().subarray(0, -22)]))).toThrow('unexpected data after its end');
    // Embedded: a valid archive whose offsets point past a whole hidden archive placed before it.
    // A reader that only follows the central directory would never look at the hidden archive.
    expect(() => readZip(zip({ 'a.txt': 'alpha' }, { prefix: hidden() }))).toThrow(
      'unexpected data between ZIP entries',
    );
  });

  test('rejects a wrong end-record comment length and real comments', async () => {
    const { readZip } = await load();
    // A correctly declared 7-byte comment: comments are never scanned, so they are rejected.
    const withComment = Buffer.concat([withEndField(clean(), 20, 7, 2), Buffer.from('comment')]);

    // Declares a 5-byte comment that is not there.
    expect(() => readZip(withEndField(clean(), 20, 5, 2))).toThrow('ZIP comments are not supported');
    expect(() => readZip(withComment)).toThrow('unexpected data after its end');
  });

  test('rejects central-directory size and offset mismatches', async () => {
    const { readZip } = await load();
    const archive = clean();
    const size = archive.readUInt32LE(archive.length - 22 + 12);
    const offset = archive.readUInt32LE(archive.length - 22 + 16);

    expect(() => readZip(withEndField(archive, 12, size - 1, 4))).toThrow('central directory does not match its size');
    expect(() => readZip(withEndField(archive, 12, size + 1, 4))).toThrow('central directory does not match its size');
    expect(() => readZip(withEndField(archive, 16, offset - 1, 4))).toThrow(
      'central directory does not match its size',
    );
    // Fewer entries than the directory holds: the remaining directory bytes are unexplained.
    expect(() => readZip(withEndField(withEndField(archive, 8, 1, 2), 10, 1, 2))).toThrow(
      'unexpected data in the ZIP central directory',
    );
    expect(() => readZip(withEndField(archive, 16, 0xffffffff, 4))).toThrow('ZIP64 archives are not supported');
  });

  test('rejects unlisted entries, gaps, prefixes and overlapping entries', async () => {
    const { readZip } = await load();
    const overlapping = clean();
    // Point the second directory entry at the first local entry.
    const secondEntry = overlapping.readUInt32LE(overlapping.length - 22 + 16) + 46 + 'a.txt'.length;
    overlapping.writeUInt32LE(0, secondEntry + 42);

    expect(() =>
      readZip(zip({ 'a.txt': 'alpha', 'secret.json': kv('token', SECRET) }, { unlisted: ['secret.json'] })),
    ).toThrow('unexpected data between ZIP entries');
    expect(() =>
      readZip(zip({ 'secret.json': kv('token', SECRET), 'a.txt': 'alpha' }, { unlisted: ['secret.json'] })),
    ).toThrow('unexpected data between ZIP entries');
    expect(() => readZip(zip({ 'a.txt': 'alpha' }, { gap: Buffer.from(kv('token', SECRET)) }))).toThrow(
      'unexpected data between ZIP entries',
    );
    expect(() => readZip(zip({ 'a.txt': 'alpha' }, { prefix: Buffer.from('junk') }))).toThrow(
      'unexpected data between ZIP entries',
    );
    expect(() => readZip(overlapping)).toThrow('unexpected data between ZIP entries');
  });

  test('scans entries that use data descriptors inside a report', async ({}, testInfo) => {
    const { scanReport } = await load();
    const dir = writeReport(
      testInfo.outputPath('report'),
      { 'a.json': '{}' },
      { 'data/trace.zip': zip({ 'trace.network': kv('token', SECRET) }, { descriptor: 'signed' }) },
    );

    expect(scanReport(dir).findings).toEqual([
      { location: 'data/trace.zip > trace.network', rule: 'json-credential', count: 1 },
    ]);
  });

  test('turns appended data in a report attachment into a scan error', async ({}, testInfo) => {
    const { main } = await load();
    const dir = writeReport(
      testInfo.outputPath('report'),
      { 'a.json': '{}' },
      { 'data/trace.zip': Buffer.concat([clean(), Buffer.from(kv('token', SECRET))]) },
    );
    const lines: string[] = [];

    expect(main([dir], (line) => lines.push(line))).toBe(2);
    expect(lines.join('\n')).not.toContain(SECRET);
  });
});

